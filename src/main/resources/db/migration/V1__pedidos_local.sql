CREATE TABLE pedidos (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id varchar(100) NOT NULL, email_usuario varchar(150) NOT NULL,
 fecha_creacion timestamp, total numeric(10,2) NOT NULL, estado varchar(30) NOT NULL,
 operacion_id uuid UNIQUE, pago_id uuid UNIQUE, tenant_id uuid,
 payment_status varchar(30), simulacion boolean NOT NULL DEFAULT false,
 checkout_payload text
);
CREATE TABLE item_pedido (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pedido_id bigint NOT NULL REFERENCES pedidos(id), producto_id bigint NOT NULL,
 nombre_producto varchar(120), cantidad integer NOT NULL, precio_unitario numeric(10,2) NOT NULL
);
