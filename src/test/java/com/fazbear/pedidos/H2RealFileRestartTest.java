package com.fazbear.pedidos;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.math.BigDecimal;
import java.nio.file.Path;
import java.sql.*;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Verificación técnica rigurosa de persistencia H2 basada en archivo para Pedidos.
 * Demuestra la conservación de datos entre conexiones independientes y
 * cierres completos de la base de datos (simulando reinicios reales de la aplicación).
 */
class H2RealFileRestartTest {

    @TempDir
    Path tempDir;

    @Test
    @DisplayName("H2 en modo archivo debe persistir pedidos y estados tras cierre total de conexiones y reapertura")
    void testH2FilePersistsPedidosAcrossIndependentConnections() throws SQLException {
        Path dbFile = tempDir.resolve("pedidosdb");
        String jdbcUrl = "jdbc:h2:file:" + dbFile.toAbsolutePath() + ";AUTO_SERVER=FALSE;DB_CLOSE_DELAY=0";

        // =========================================================================
        // SESIÓN 1: Primera ejecución (creación de esquema e inserción de pedido)
        // =========================================================================
        try (Connection conn = DriverManager.getConnection(jdbcUrl, "sa", "")) {
            assertThat(conn).isNotNull();
            try (Statement stmt = conn.createStatement()) {
                stmt.execute("""
                    CREATE TABLE pedidos (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        usuario_id VARCHAR(100) NOT NULL,
                        email_usuario VARCHAR(150) NOT NULL,
                        total DECIMAL(10, 2) NOT NULL,
                        estado VARCHAR(30) NOT NULL,
                        fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        simulacion BOOLEAN DEFAULT FALSE
                    )
                """);
                stmt.execute("""
                    CREATE TABLE items_pedido (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        pedido_id BIGINT NOT NULL,
                        producto_id BIGINT NOT NULL,
                        nombre_producto VARCHAR(120),
                        cantidad INT NOT NULL,
                        precio_unitario DECIMAL(10, 2) NOT NULL,
                        CONSTRAINT fk_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos(id)
                    )
                """);

                stmt.execute("""
                    INSERT INTO pedidos (usuario_id, email_usuario, total, estado, simulacion)
                    VALUES ('user-oid-100', 'cliente@fazbear.com', 45.00, 'PENDIENTE', TRUE)
                """);
                stmt.execute("""
                    INSERT INTO items_pedido (pedido_id, producto_id, nombre_producto, cantidad, precio_unitario)
                    VALUES (1, 201, 'Combo Familiar Freddy', 1, 45.00)
                """);
            }
        }
        // Base de datos H2 completamente cerrada en disco.

        // =========================================================================
        // SESIÓN 2: Segunda ejecución independiente (reinicio contra el mismo archivo)
        // =========================================================================
        try (Connection conn2 = DriverManager.getConnection(jdbcUrl, "sa", "")) {
            assertThat(conn2).isNotNull();
            try (Statement stmt = conn2.createStatement()) {
                try (ResultSet rs = stmt.executeQuery("SELECT id, usuario_id, email_usuario, total, estado FROM pedidos WHERE id = 1")) {
                    assertThat(rs.next()).isTrue();
                    assertThat(rs.getLong("id")).isEqualTo(1L);
                    assertThat(rs.getString("usuario_id")).isEqualTo("user-oid-100");
                    assertThat(rs.getString("email_usuario")).isEqualTo("cliente@fazbear.com");
                    assertThat(rs.getBigDecimal("total")).isEqualByComparingTo(new BigDecimal("45.00"));
                    assertThat(rs.getString("estado")).isEqualTo("PENDIENTE");
                }

                // Cambiar estado del pedido en la sesión 2
                stmt.execute("UPDATE pedidos SET estado = 'PREPARANDO' WHERE id = 1");
            }
        }
        // Segunda desconexión completa.

        // =========================================================================
        // SESIÓN 3: Tercera ejecución (comprobar que la mutación persistió tras nuevo reinicio)
        // =========================================================================
        try (Connection conn3 = DriverManager.getConnection(jdbcUrl, "sa", "")) {
            try (Statement stmt = conn3.createStatement()) {
                try (ResultSet rs = stmt.executeQuery("SELECT estado FROM pedidos WHERE id = 1")) {
                    assertThat(rs.next()).isTrue();
                    assertThat(rs.getString("estado")).isEqualTo("PREPARANDO");
                }
            }
        }
    }
}
